import {test} from 'node:test';import assert from 'node:assert/strict';
import {makePlan,Writer,validateFrames} from '../writer.mjs';
import {decodeRadio} from '../radio-decoder.mjs';
import {readDat,writeDat} from '../dat.mjs';
import {emptyChannel,insertChannel,moveChannel,removeChannels} from '../channels.mjs';
import {appendChannels} from '../channel-import.mjs';
import {fixture,channel,options,schemas} from './fixtures.mjs';
import {simulatedRadio} from './simulate.mjs';import {appHarness} from './app-harness.mjs';

// Literal bytes from F08-CHANNEL999.json, captured after the factory wired CPS write.
// These expectations are not generated by the encoder being tested.
const stored=Buffer.from('006f6523006f65230000000000000000ffffffff057f3863061c54ffffffffffffffffffffffffffffffffffffffffffffffffffffffffffffffffffffffffff','hex');
const alternating=Buffer.from('00206514002065140000000000000000ffffffff46303854455354ffffffffffffffffffffffffffffffffffffffffffffffffffffffffffffffffffffffffff','hex');
const tail=Buffer.concat(Array.from({length:13},(_,i)=>i%2?alternating:stored));
const with999=()=>{const d=fixture();d.channelList[0][998]=channel('F08TEST');return d;};
const bytes=(p,a=0x7cc0,b=0x8000)=>Buffer.from(p.target.subarray(a,b));

test('F08: channel 999 and all twelve trailing blocks match independent physical bytes',()=>{
 const d=with999(),p=makePlan(d,options);assert.deepEqual(bytes(p),tail);
 assert.equal(p.frames.length,262);validateFrames(p.frames);
 assert.deepEqual(decodeRadio(p.target).channelList[0][998],d.channelList[0][998]);
 assert.equal(decodeRadio(p.target).channelList[0][999].rxFreq,'');
 assert.deepEqual(readDat(writeDat(d,schemas),schemas),d);
});
test('F08: channel 998 occupies 0x7CA0 and does not change the channel-999 tail',()=>{
 const d=with999(),before=makePlan(d,options);d.channelList[0][997]=channel('EDGE998','446.00000');const after=makePlan(d,options);
 const differences=[...before.target.keys()].filter(i=>before.target[i]!==after.target[i]);
 assert.ok(differences.length>0);assert.ok(differences.every(i=>i>=0x7ca0&&i<0x7cc0));assert.deepEqual(bytes(after),tail);
 assert.equal(decodeRadio(after.target).channelList[0][997].name,'EDGE998');
});
test('F08: editing an ordinary channel preserves the complete populated final region',()=>{
 const d=with999(),before=makePlan(d,options);d.channelList[0][70]={...channel('F06TEST'),txPower:1};const after=makePlan(d,options);
 const differences=[...before.target.keys()].filter(i=>before.target[i]!==after.target[i]);
 assert.equal(differences.length,23);assert.ok(differences.every(i=>i>=0x8c0&&i<0x8e0));assert.deepEqual(bytes(after),tail);
});
test('F08: explicit deletion clears every repeated record and only that region',()=>{
 const d=with999(),before=makePlan(d,options),next=removeChannels(d,[998]),after=makePlan(next,options);
 assert.ok(bytes(after).every(b=>b===255));assert.equal(d.channelList[0][998].name,'F08TEST');
 const differences=[...before.target.keys()].filter(i=>before.target[i]!==after.target[i]);assert.equal(differences.length,299);
 assert.ok(differences.every(i=>i>=0x7cc0&&i<0x8000));
});
test('F08: changing channel 999 updates all thirteen records without touching other sections',()=>{
 const d=with999(),before=makePlan(d,options);d.channelList[0][998].name='F08EDIT';const after=makePlan(d,options);
 const differences=[...before.target.keys()].filter(i=>before.target[i]!==after.target[i]);
 assert.equal(differences.length,39);assert.ok(differences.every(i=>i>=0x7cc0&&i<0x8000));
 for(let a=0x7cc0;a<0x8000;a+=64)assert.notDeepEqual(bytes(after,a,a+32),bytes(before,a,a+32));
 assert.equal(decodeRadio(after.target).channelList[0][998].name,'F08EDIT');
});
test('F08: unsupported record 1000 stays blocked and intact in DAT export',()=>{
 for(const rx of ['', '146.52000']){const d=with999();d.channelList[0][998].rxFreq=rx;d.channelList[0][998].txFreq=rx;d.channelList[0][999]=channel('UNSUPPORTED');
 assert.throws(()=>makePlan(d,options),/1000.*not supported/i);assert.deepEqual(readDat(writeDat(d,schemas),schemas),d);}
});
test('F08: insert, move and append reach 999 without using reserved record 1000',()=>{
 const base=fixture();base.channelList[0][999].name='KEEP';
 const inserted=insertChannel(base,998,channel('F08TEST')),moved=moveChannel(inserted,998,997);
 for(const d of [inserted,moved]){assert.deepEqual(d.channelList[0][999],base.channelList[0][999]);makePlan(d,options);assert.deepEqual(readDat(writeDat(d,schemas),schemas),d);}
 const filled=fixture();for(let i=0;i<998;i++)filled.channelList[0][i]=channel('OCCUPIED');filled.channelList[0][999].name='KEEP';
 const appended=appendChannels(filled,[channel('F08TEST')],{skipDuplicates:false});assert.equal(appended.plan.start,999);
 assert.deepEqual(bytes(makePlan(appended.data,options)),tail);assert.equal(appended.data.channelList[0][999].name,'KEEP');
 assert.throws(()=>appendChannels(appended.data,[channel('FULL')],{skipDuplicates:false}),/Not enough/);
});
test('F08: simulated full write/readback retains 999 with unchanged 262-frame transaction',async()=>{
 const p=makePlan(with999(),options),w=new Writer(),sim=simulatedRadio(w);try{
 await w.upload(p,null,{confirmed:true});assert.equal(sim.writes().length,262);assert.equal(w.report.verified,false);
 const result=await w.verify(p,null);assert.equal(result.differences.total,0);assert.deepEqual(bytes({target:result.raw}),tail);assert.equal(sim.writes().length,262);
 }finally{w.disconnect();}
});
test('F08: real UI handlers retain 999 through ordinary editing and explicit confirmation',async()=>{
 const h=await appHarness();try{
 await h.open(with999());h.row(0).querySelectorAll('button').find(b=>b.textContent==='Edit').click();h.enter('name','EDITED');h.get('apply').click();
 assert.equal((await h.exported()).channelList[0][998].name,'F08TEST');h.get('writeRadio').click();assert.equal(h.get('warning').open,true);assert.equal(h.connections.length,0);
 h.get('hasBackup').checked=true;h.get('hasBackup').onchange();await h.get('confirmWrite').click();assert.equal(h.connections[0].writes().length,262);assert.equal(h.radio.report.stage,'written-unverified');
 }finally{h.radio.disconnect();h.close();}
});
